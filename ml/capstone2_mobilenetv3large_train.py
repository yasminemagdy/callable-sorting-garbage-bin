# =========================
# Offline Augmentation for Class Balancing
# =========================

from tensorflow.keras.preprocessing.image import ImageDataGenerator, img_to_array, load_img
import numpy as np
from tqdm import tqdm

datagen = ImageDataGenerator(
    rotation_range=30,
    width_shift_range=0.2,
    height_shift_range=0.2,
    shear_range=0.2,
    zoom_range=0.2,
    horizontal_flip=True,
    brightness_range=[0.8, 1.2],
    fill_mode="nearest"
)

for cls, count in class_counts.items():

    if count < target_count:

        print(f"\nAugmenting class: {cls} ({count} → {target_count})")

        cls_dir = os.path.join(new_dataset_path, cls)

        images = [
            os.path.join(cls_dir, f)
            for f in os.listdir(cls_dir)
            if f.lower().endswith(("jpg", "jpeg", "png"))
        ]

        n_needed = target_count - count
        added = 0

        while added < n_needed:

            img_path = images[added % len(images)]

            img = load_img(img_path)
            x = img_to_array(img)
            x = np.expand_dims(x, axis=0)

            for batch in datagen.flow(
                x,
                batch_size=1,
                save_to_dir=cls_dir,
                save_prefix=f"aug_{cls}",
                save_format="jpg"
            ):
                added += 1

                if added >= n_needed:
                    break

        print(f"Done: added {n_needed} images to {cls}")

print("\nAugmentation completed!")

